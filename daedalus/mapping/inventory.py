"""inventory -- the GENERATED feature census.

``docs/FEATURE_INVENTORY.json`` used to be typed by hand. It stamped the
revision it was written against and then sat there while thirty commits landed
on top of it, and because the self-improvement picker reads its two highest
bands, the thing that chooses what gets worked on next was reasoning about a
tree that no longer existed. The repo's own narrative records the size of that
failure mode: a hand-written inventory listed 136 features where a deep read of
the same tree found 827.

This module replaces the typing. It derives every mechanical field from the
same single walk of the tree that ``daedalus map`` already performs
(:func:`daedalus.mapping.render.analyse_once`), so the census cannot be older
than the run that produced it.

WHAT IS DERIVABLE, AND WHAT IS NOT
----------------------------------
Derivable, and therefore regenerated on every run:

  * the module census and its ``status`` -- wired / island / shim / unknown --
    straight off :func:`daedalus.mapping.reach.analyse`'s classification;
  * ``entrypoints``, ``entry_kinds``, ``importers`` and ``tests`` per module;
  * the CLI dispatch table and the HTTP route table, from the entry points;
  * every environment switch, where it is read, whether it is dark and whether
    any document mentions it, from :mod:`daedalus.mapping.switches`;
  * two kinds of ``stale``: a package this repo's own packaging metadata
    promises that is not on disk, and a ``__pycache__`` whose sources are gone;
  * the packaging gap in the other direction -- a package on disk that a wheel
    would not contain.

NOT derivable, and therefore preserved rather than invented:

  * ``notes`` -- WHY a thing is the way it is. No scanner derives that.
  * ``kind`` -- the semantic taxonomy (safety / orchestration / provider /
    memory). A path prefix is a hint, not a fact.
  * ``name`` -- the human-legible name of a capability, as opposed to the file
    it happens to live in.
  * ``status: planned`` and ``status: baseline`` -- a feature that has no code
    yet has no evidence a scanner can read, and "this is deliberately only a
    baseline" is a judgement.
  * every feature whose surface is not Python: the web app, the VS Code
    extension, the crew protocol files. The reachability engine walks ``.py``;
    claiming to have measured a ``.tsx`` would be a lie of scope.

THE MERGE
---------
Mechanical fields are rewritten every run. Human fields live in ``annotations``
(keyed to a module, an env var or a route) and ``narrative_features`` (whole
hand-written entries with no mechanical counterpart), and are merged into the
output for consumers -- but the ``digest`` is computed over a projection that
strips them again. So:

  * editing a note, a name or a kind is legal and does not trip the gate;
  * editing a ``status``, a test list or an island entry DOES trip it, because
    that is the half a human is not supposed to write.

That is a refinement of the rule :func:`daedalus.mapping.drift._digest` states
for the map snapshot, where the human half is a whole top-level block. Here the
human half is interleaved with the mechanical half by field, so the digest is
taken over a projection instead of over a key list.

Annotations carry human fields ONLY. An annotation cannot set ``status`` and
cannot add a module, because the failure being fixed is a hand-written file
steering the work queue -- handing that same power back through a side door
would be the same defect wearing a generated file's clothes.
"""
