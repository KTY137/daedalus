def inventory_bytes(doc: Mapping[str, Any]) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def load(path) -> dict | None:
    p = Path(path)
    if not p.is_file():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {"__error__": str(exc)}


def write_inventory(path, doc: Mapping[str, Any]) -> str:
    text = inventory_bytes(doc)
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    return text


def refresh(repo_root, path=None, *, index=None, reports=None,
            probe_dirty: bool = True) -> dict:
    """Regenerate in place, carrying the human half forward.

    The old document is read for its annotations BEFORE it is overwritten, and
    a first run over a schema-1 file harvests them out of the hand-written
    entries. Refreshing is never a way to quietly drop somebody's stated
    reason.
    """
    root = Path(repo_root).resolve()
    target = Path(path) if path else root / INVENTORY_REL
    old = load(target) or {}
    if old.get("__error__"):
        old = {}

    from . import render as render_mod

    reports = reports or render_mod.analyse_once(root, index)
    reach_report, switch_report = reports
    modules = [m.module for m in reach_report.modules]
    env_names = [s.name for s in switch_report.env_switches]
    annotations, narrative, stats = harvest(old, modules, env_names)

    doc = build(root, reports=reports, annotations=annotations,
                narrative_features=narrative, probe_dirty=probe_dirty)
    write_inventory(target, doc)
    return {"path": str(target), "doc": doc, "harvest": stats}


def check(repo_root, path=None, *, index=None, reports=None,
          probe_dirty: bool = True) -> dict:
    """Gate mode. Writes nothing; returns ``{"ok": bool, "problems": [...]}``.

    Four ways to fail, in the order a reader needs them:
      1. there is no inventory, or it cannot be parsed;
      2. it was written by a different schema;
      3. its digest does not cover its own derived fields -- somebody edited
         the mechanical half by hand;
      4. regenerating it now would change something -- it is STALE, and the
         diff says exactly how.
    """
    root = Path(repo_root).resolve()
    target = Path(path) if path else root / INVENTORY_REL
    problems: list[str] = []

    stored = load(target)
    if stored is None:
        return {"ok": False, "path": str(target), "problems": [
            f"no inventory at {target}: nothing generated it. Run "
            f"`python -m daedalus.mapping.inventory --refresh`"]}
    if stored.get("__error__"):
        return {"ok": False, "path": str(target), "problems": [
            f"{target} could not be parsed: {stored['__error__']}"]}
    if stored.get("schema") != SCHEMA:
        return {"ok": False, "path": str(target), "problems": [
            f"{target} carries schema {stored.get('schema')!r}; this build "
            f"generates and compares {SCHEMA!r}"]}
    if not digest_ok(stored):
        problems.append(
            "the derived fields do not match the digest written with them: "
            "something was hand-edited. Pre-seeding a status, an island or a "
            "test list is not a way to steer the work queue")

    over = annotation_overreach(stored.get("annotations") or {})
    for entry in over:
        problems.append(f"annotation carries fields a human may not set -- {entry}")

    from . import render as render_mod

    reports = reports or render_mod.analyse_once(root, index)
    fresh = build(root, reports=reports,
                  annotations=stored.get("annotations") or {},
                  narrative_features=stored.get("narrative_features") or [],
                  probe_dirty=probe_dirty)

    old_body = _strip_human(stored)
    new_body = _strip_human(fresh)
    if old_body != new_body:
        problems.extend(_describe_drift(stored, fresh))

    return {"ok": not problems, "path": str(target), "problems": problems,
            "stored": stored, "fresh": fresh}


def _by_key(doc: Mapping[str, Any]) -> dict[str, dict]:
    """Every feature's DERIVED half, keyed by module (or by detector for the
    module-less stale entries). The human fields are dropped so a note cannot
    read as drift."""
    out: dict[str, dict] = {}
    for area in doc.get("areas") or []:
        for feat in (area or {}).get("features") or []:
            key = feat.get("module") or f"{feat.get('detector')}:{feat.get('reason')}"
            out[str(key)] = {k: v for k, v in feat.items()
                             if k not in FEATURE_HUMAN_FIELDS}
    return out


def _statuses(doc: Mapping[str, Any]) -> dict[str, str]:
    return {k: str(v.get("status")) for k, v in _by_key(doc).items()}


def _describe_drift(stored: Mapping[str, Any], fresh: Mapping[str, Any]) -> list[str]:
    out: list[str] = []
    old_head = (stored.get("repo_state") or {}).get("head")
    new_head = (fresh.get("repo_state") or {}).get("head")
    if old_head != new_head:
        out.append(f"written against {str(old_head)[:12]}; HEAD is "
                   f"{str(new_head)[:12]}")
    old_status = _statuses(stored)
    new_status = _statuses(fresh)
    for key in sorted(set(new_status) - set(old_status)):
        out.append(f"new feature {key} ({new_status[key]})")
    for key in sorted(set(old_status) - set(new_status)):
        out.append(f"feature gone: {key} (was {old_status[key]})")
    for key in sorted(set(old_status) & set(new_status)):
        if old_status[key] != new_status[key]:
            out.append(f"{key}: {old_status[key]} -> {new_status[key]}")
    for block in ("env_vars", "cli_commands", "api_endpoints", "invocations",
                  "bus_loops", "packaging"):
        if (stored.get(block) or []) != (fresh.get(block) or []):
            out.append(f"{block} moved")
    # Field-level, not just status-level. A module whose importers or reaching
    # entry point changed is a real difference, and reporting it as "something
    # differs, go diff the file yourself" is how a gate stops being read.
    old_feats, new_feats = _by_key(stored), _by_key(fresh)
    moved: list[str] = []
    for key in sorted(set(old_feats) & set(new_feats)):
        old_f, new_f = old_feats[key], new_feats[key]
        if old_f == new_f:
            continue
        fields = sorted(k for k in set(old_f) | set(new_f)
                        if old_f.get(k) != new_f.get(k) and k != "status")
        if fields:
            moved.append(f"{key}: {', '.join(fields)} changed")
    out.extend(moved[:10])
    if len(moved) > 10:
        out.append(f"... and {len(moved) - 10} more modules whose derived "
                   f"fields changed")
    if not out:
        out.append("the derived half differs from a fresh scan (no headline "
                   "difference; compare the file with --json)")
    return out


def render_text(doc: Mapping[str, Any]) -> str:
    counts = doc.get("counts") or {}
    state = doc.get("repo_state") or {}
    lines = [
        f"feature inventory: {SCHEMA}",
        f"  rev {str(state.get('head') or 'unknown')[:12]} on "
        f"{state.get('branch')} - dirty={state.get('dirty')}",
        "  modules=%s  wired=%s island=%s shim=%s unknown=%s stale=%s" % (
            counts.get("modules", 0), counts.get("status_wired", 0),
            counts.get("status_island", 0), counts.get("status_shim", 0),
            counts.get("status_unknown", 0), counts.get("status_stale", 0)),
        "  cli=%s api=%s bus=%s env=%s (dark %s)  packaging_gaps=%s" % (
            counts.get("cli_commands", 0), counts.get("api_endpoints", 0),
            counts.get("bus_loops", 0), counts.get("env_vars", 0),
            counts.get("dark_env_vars", 0), counts.get("packaging_gaps", 0)),
        "  human: %s annotations, %s narrative features, %s unmatched" % (
            counts.get("annotations", 0), counts.get("narrative_features", 0),
            len(doc.get("unmatched_annotations") or [])),
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m daedalus.mapping.inventory",
        description="Generate docs/FEATURE_INVENTORY.json from the live tree. "
                    "Mechanical fields are rewritten every run; human notes are "
                    "carried forward and excluded from the digest.")
    ap.add_argument("--repo", default=".")
    ap.add_argument("--out", default=None, help=f"default {INVENTORY_REL}")
    ap.add_argument("--refresh", action="store_true",
                    help="regenerate the file in place")
    ap.add_argument("--check", action="store_true",
                    help="gate mode: exit non-zero if the file is missing, "
                         "hand-edited or stale; writes nothing")
    ap.add_argument("--json", action="store_true",
                    help="print the generated document; writes nothing")
    ap.add_argument("--no-git", action="store_true",
                    help="skip the working-tree dirty probe")
    args = ap.parse_args(list(argv) if argv is not None else None)

    root = Path(args.repo).resolve()
    target = Path(args.out) if args.out else root / INVENTORY_REL
    probe = not args.no_git

    if args.check:
        report = check(root, target, probe_dirty=probe)
        if report["ok"]:
            print(f"inventory: OK -- {report['path']} matches a fresh scan")
            return 0
        print(f"inventory: STALE or INVALID -- {report['path']}")
        for problem in report["problems"]:
            print(f"  - {problem}")
        print("\nRegenerate with `python -m daedalus.mapping.inventory "
              "--refresh` (or `daedalus map`, which does it as part of the run).")
        return 1

    if args.json:
        old = load(target) or {}
        from . import render as render_mod

        reports = render_mod.analyse_once(root)
        modules = [m.module for m in reports[0].modules]
        env_names = [s.name for s in reports[1].env_switches]
        annotations, narrative, _ = harvest(old, modules, env_names)
        doc = build(root, reports=reports, annotations=annotations,
                    narrative_features=narrative, probe_dirty=probe)
        print(json.dumps(doc, indent=2, ensure_ascii=False))
        return 0

    if not args.refresh:
        ap.error("nothing to do: pass --refresh, --check or --json")

    result = refresh(root, target, probe_dirty=probe)
    print(render_text(result["doc"]))
    stats = result["harvest"]
    if stats.get("old_features"):
        print(f"  harvested {stats['matched']} annotated + "
              f"{stats['narrative']} narrative from {stats['old_features']} "
              f"hand-written features, {stats['env']} env purposes")
    print(f"  wrote {result['path']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
