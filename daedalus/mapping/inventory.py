def _strip_human(doc: Mapping[str, Any]) -> dict:
    """The mechanical projection of a whole document.

    Everything a human is allowed to write is removed: the human top-level
    blocks, and the human FIELDS interleaved into the generated records. What
    is left is exactly what this module derives, which is exactly what a digest
    should be a function of.
    """
    body: dict[str, Any] = {}
    for key, value in doc.items():
        if key in _HUMAN_TOP_KEYS:
            continue
        if key == "areas":
            areas = []
            for area in value or []:
                if not isinstance(area, Mapping):
                    continue
                features = []
                for feat in area.get("features") or []:
                    if not isinstance(feat, Mapping):
                        continue
                    features.append({k: v for k, v in feat.items()
                                     if k not in FEATURE_HUMAN_FIELDS})
                areas.append({
                    **{k: v for k, v in area.items()
                       if k not in AREA_HUMAN_FIELDS and k != "features"},
                    "features": features,
                })
            body[key] = areas
        elif key == "env_vars":
            body[key] = [{k: v for k, v in row.items()
                          if k not in ENV_HUMAN_FIELDS}
                         for row in value or [] if isinstance(row, Mapping)]
        elif key == "repo_state":
            # The revision, and only the revision. ``branch`` and ``dirty``
            # move without the architecture moving, and a gate that goes red
            # because somebody has unsaved edits is a gate people switch off.
            state = value if isinstance(value, Mapping) else {}
            body[key] = {"head": state.get("head")}
        else:
            body[key] = value
    return body


def _digest(doc: Mapping[str, Any]) -> str:
    """A hash over the derived half only. Canonical JSON, sorted keys, so the
    value is a function of the content and not of the writer's key order."""
    blob = json.dumps(_strip_human(doc), sort_keys=True, ensure_ascii=False,
                      separators=(",", ":"))
    return "sha256:" + hashlib.sha256(blob.encode("utf-8")).hexdigest()


def digest_ok(doc: Any) -> bool:
    """Does this document's own digest still cover its own derived fields?

    Public for the same reason :func:`daedalus.mapping.drift.digest_ok` is: any
    consumer that RANKS WORK out of these lists rather than rescanning has to
    ask this first. Ranking work out of a hand-edited census is precisely the
    defect this module was written to end.
    """
    if not isinstance(doc, Mapping) or doc.get("__error__"):
        return False
    return doc.get(DIGEST_KEY) == _digest(doc)


