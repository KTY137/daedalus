def _area_of(rel: str) -> str:
    parent = rel.rsplit("/", 1)[0] if "/" in rel else ""
    return parent or "(repo root)"


def _dotted(rel: str) -> str:
    stem = rel[:-3] if rel.endswith(".py") else rel
    if stem.endswith("/__init__"):
        stem = stem[: -len("/__init__")]
    return stem.replace("/", ".")


def _method_of(function: str) -> str:
    for suffix, method in _METHOD_BY_SUFFIX:
        if function.endswith(suffix):
            return method
    return ""


def _pyproject_packages(root: Path) -> list[str]:
    """The explicit ``[tool.setuptools] packages`` list, or ``[]``.

    A line scanner rather than a TOML parser: this module is stdlib-only across
    3.10 (no ``tomllib``), and the shape being read is one array under one
    known table. An unreadable or absent pyproject yields an empty list, which
    both detectors below read as "no promise was made" -- never as a finding.
    """
    path = root / "pyproject.toml"
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    out: list[str] = []
    in_table = False
    in_array = False
    for line in text.splitlines():
        if in_array:
            out.extend(_QUOTED_RE.findall(line))
            if "]" in line:
                in_array = False
                break
            continue
        if _SCRIPTS_HEADER.match(line):
            in_table = True
            continue
        if in_table and _SECTION_RE.match(line):
            break
        if not in_table:
            continue
        m = _PACKAGES_RE.match(line)
        if not m:
            continue
        rest = m.group(1)
        out.extend(_QUOTED_RE.findall(rest))
        if "]" not in rest:
            in_array = True
    return sorted(set(out))


def _packages_on_disk(root: Path, listed: Sequence[str]) -> list[str]:
    """Dotted packages that exist under the distribution roots the metadata
    already names. Scoped to those roots on purpose: every directory in the
    repo with an ``__init__.py`` is not a candidate for the wheel, and treating
    a fixture or a runs/ directory as one would manufacture findings."""
    roots = sorted({name.split(".", 1)[0] for name in listed})
    found: list[str] = []
    for top in roots:
        base = root / top
        if not base.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames
                                 if d not in _STALE_SKIP_DIRS
                                 and not d.startswith("."))
            if "__init__.py" not in filenames:
                continue
            rel = Path(dirpath).relative_to(root).as_posix()
            found.append(rel.replace("/", "."))
    return sorted(set(found))


def _orphan_bytecode(root: Path) -> list[tuple[str, int]]:
    """``__pycache__`` directories holding bytecode whose sources are gone.

    The exact shape of the ``daedalus/hermes`` remnant the hand-written
    inventory recorded: the package was deleted, the ``.pyc`` files stayed, and
    an import of the dotted name could still resolve. A cache beside live
    sources is not a finding -- only one with NO sibling ``.py`` at all.
    """
    out: list[tuple[str, int]] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in _STALE_SKIP_DIRS)
        if Path(dirpath).name != "__pycache__":
            continue
        pyc = [f for f in filenames if f.endswith(".pyc")]
        if not pyc:
            continue
        parent = Path(dirpath).parent
        try:
            siblings = [f for f in os.listdir(parent) if f.endswith(".py")]
        except OSError:
            continue
        if siblings:
            continue
        out.append((Path(dirpath).relative_to(root).as_posix(), len(pyc)))
    return sorted(out)


