def _clean_annotation(raw: Any, allowed: Sequence[str]) -> dict:
    if not isinstance(raw, Mapping):
        return {}
    out = {}
    for key in allowed:
        value = raw.get(key)
        if isinstance(value, str) and value.strip():
            out[key] = value.strip()
    return out


def annotation_overreach(annotations: Mapping[str, Any]) -> list[str]:
    """Annotation keys carrying fields a human is NOT allowed to set.

    Reported rather than silently dropped. Silently dropping is how a person
    concludes the field works; naming it is how they learn the rule. The build
    ignores these fields either way -- an annotation that could set ``status``
    would hand the hand-written file's exact power back through a side door.
    """
    allowed = set(FEATURE_HUMAN_FIELDS) | set(ENV_HUMAN_FIELDS) | set(AREA_HUMAN_FIELDS)
    bad: list[str] = []
    for key, value in sorted((annotations or {}).items()):
        if not isinstance(value, Mapping):
            bad.append(f"{key}: not an object")
            continue
        extra = sorted(set(value) - allowed)
        if extra:
            bad.append(f"{key}: {', '.join(extra)}")
    return bad


def _module_targets(feature: Mapping[str, Any], known: Iterable[str]) -> list[str]:
    """Every module a hand-written feature's entrypoints resolve to.

    ALL of them, not the first: the kairos-rename shim entry names five modules
    in one feature, and attaching its rationale to only one of them would lose
    the reason for the other four.
    """
    known_set = set(known)
    hits: list[str] = []
    raw = feature.get("entrypoints")
    if isinstance(raw, str):
        raw = [raw]
    for entry in raw or []:
        for token in _TOKEN_RE.findall(str(entry)):
            cand = token.replace("\\", "/")
            if cand.endswith(".py"):
                if cand in known_set and cand not in hits:
                    hits.append(cand)
                continue
            if "/" in cand or "." not in cand:
                continue
            stem = cand.replace(".", "/")
            for rel in (stem + ".py", stem + "/__init__.py"):
                if rel in known_set and rel not in hits:
                    hits.append(rel)
    return hits


def harvest(old: Mapping[str, Any], modules: Sequence[str],
            env_names: Sequence[str] = ()) -> tuple[dict, list, dict]:
    """Lift the human half out of a previous inventory. LOSSLESS by contract.

    Returns ``(annotations, narrative_features, stats)``. Every feature in the
    old document ends up in exactly one of the two: an annotation keyed to the
    module(s) its entrypoints name, or a verbatim narrative feature. Nothing is
    dropped, because a generated file that discards the rationale somebody
    wrote is not progress -- it is the same rot with a fresher timestamp.

    Already-schema-2 documents pass their blocks straight through; the harvest
    only has work to do the first time.
    """
    annotations: dict[str, dict] = {}
    narrative: list[dict] = []
    stats = {"old_features": 0, "matched": 0, "narrative": 0, "env": 0}

    if not isinstance(old, Mapping) or not old:
        return annotations, narrative, stats

    if old.get("schema") == SCHEMA:
        raw_ann = old.get("annotations")
        if isinstance(raw_ann, Mapping):
            for key, value in raw_ann.items():
                cleaned = _clean_annotation(
                    value, FEATURE_HUMAN_FIELDS + ENV_HUMAN_FIELDS
                    + AREA_HUMAN_FIELDS)
                if cleaned:
                    annotations[str(key)] = cleaned
        raw_narr = old.get("narrative_features")
        if isinstance(raw_narr, (list, tuple)):
            narrative = [dict(f) for f in raw_narr if isinstance(f, Mapping)]
        stats["matched"] = len(annotations)
        stats["narrative"] = len(narrative)
        return annotations, narrative, stats

    known = set(modules)
    for area in old.get("areas") or []:
        if not isinstance(area, Mapping):
            continue
        area_name = str(area.get("area") or "")
        for feature in area.get("features") or []:
            if not isinstance(feature, Mapping):
                continue
            stats["old_features"] += 1
            targets = _module_targets(feature, known)
            human = {}
            for field_name in FEATURE_HUMAN_FIELDS:
                value = feature.get(field_name)
                if isinstance(value, str) and value.strip():
                    human[field_name] = value.strip()
            if not targets:
                entry = dict(feature)
                entry["area"] = area_name
                narrative.append(entry)
                stats["narrative"] += 1
                continue
            stats["matched"] += 1
            for rel in targets:
                key = "module:" + rel
                existing = annotations.get(key)
                if existing is None:
                    annotations[key] = dict(human)
                    continue
                # Two hand-written features naming one module. Both reasons are
                # kept, joined, rather than one silently winning.
                for field_name, value in human.items():
                    prior = existing.get(field_name, "")
                    if not prior:
                        existing[field_name] = value
                    elif value not in prior:
                        existing[field_name] = f"{prior} | {value}"

    env_known = set(env_names)
    for row in old.get("env_vars") or []:
        if not isinstance(row, Mapping):
            continue
        name = str(row.get("name") or "").strip()
        purpose = str(row.get("purpose") or "").strip()
        if not name or not purpose:
            continue
        stats["env"] += 1
        key = "env:" + name
        if name in env_known or key not in annotations:
            annotations.setdefault(key, {})["purpose"] = purpose

    return annotations, narrative, stats


