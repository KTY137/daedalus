def _feature(rel: str, facts, entry_idents: Sequence[str],
             dark_by_module: Mapping[str, Sequence[str]],
             annotation: Mapping[str, str]) -> dict:
    status = STATUS_BY_CLASS.get(facts.classification, facts.classification)
    out = {
        "module": rel,
        "status": status,
        "classification": facts.classification,
        "reason": facts.reason,
        "entry_kinds": sorted({i.split(":", 1)[0] for i in entry_idents}),
        "entrypoints": list(entry_idents),
        "reached_from": facts.entry,
        "tests": list(facts.tested_by),
        "importers": list(facts.imported_by),
        "dark_switches": list(dark_by_module.get(rel, ())),
        # human, merged for the reader, stripped before the digest
        "name": annotation.get("name") or rel,
        "kind": annotation.get("kind") or "",
        "notes": annotation.get("notes") or "",
    }
    return out


def _stale_features(root: Path, annotations: Mapping[str, Mapping[str, str]]
                    ) -> tuple[list[dict], dict]:
    """The two mechanically-detectable kinds of staleness, plus the packaging
    picture they come from.

    Deliberately only two. "This directory is a superseded experiment" and
    "this mockup was replaced by the shipped app" are judgements about intent,
    and a scanner that guessed at them would fill the work queue with its own
    guesses. They stay in ``narrative_features``, where a human signed them.
    """
    listed = _pyproject_packages(root)
    on_disk = _packages_on_disk(root, listed)
    ghosts = [p for p in listed if p not in set(on_disk)]
    gaps = [p for p in on_disk if p not in set(listed)]
    orphans = _orphan_bytecode(root)

    features: list[dict] = []
    for pkg in ghosts:
        key = "stale:package:" + pkg
        ann = annotations.get(key, {})
        features.append({
            "module": "",
            "status": STATUS_STALE,
            "detector": "packaging_ghost",
            "reason": (f"pyproject.toml [tool.setuptools] packages promises "
                       f"{pkg!r}, and no directory with an __init__.py answers "
                       f"to that name -- a non-editable install would ship a "
                       f"package that is not there"),
            "entrypoints": ["pyproject.toml [tool.setuptools] packages"],
            "tests": [],
            "name": ann.get("name") or f"packaging ghost: {pkg}",
            "kind": ann.get("kind") or "",
            "notes": ann.get("notes") or "",
        })
    for rel, count in orphans:
        key = "stale:bytecode:" + rel
        ann = annotations.get(key, {})
        features.append({
            "module": "",
            "status": STATUS_STALE,
            "detector": "orphan_bytecode",
            "reason": (f"{rel} holds {count} .pyc file(s) and its parent "
                       f"directory contains no .py source at all -- the module "
                       f"was deleted and its bytecode was not"),
            "entrypoints": [rel],
            "tests": [],
            "name": ann.get("name") or f"orphan bytecode: {rel}",
            "kind": ann.get("kind") or "",
            "notes": ann.get("notes") or "",
        })

    packaging = {
        "listed": listed,
        "on_disk": on_disk,
        # Reported, NOT filed as a stale feature. Its remedy is "add it to the
        # list", the exact opposite verb from the stale remedy ("remove it"),
        # and handing a fixer the wrong verb is how a finding becomes damage.
        "on_disk_but_unlisted": gaps,
        "listed_but_absent": ghosts,
    }
    return features, packaging


def build(repo_root, *, index=None, reports=None, annotations=None,
          narrative_features=None, probe_dirty: bool = True,
          head: str | None = None, branch: str | None = None,
          dirty: bool | None = None) -> dict:
    """Derive the whole document. Writes nothing.

    ``reports`` is the ``(reach, switches)`` pair from
    :func:`daedalus.mapping.render.analyse_once`. When it is not supplied this
    calls that function -- which is the configuration the PRODUCT uses, index
    and all. Calling ``reach.analyse(root)`` with no index here would be a
    second engine configuration that ships to nobody, and the last time a guard
    did that a CRITICAL survived underneath it.
    """
    from . import render as render_mod

    root = Path(repo_root).resolve()
    reach_report, switch_report = reports or render_mod.analyse_once(root, index)

    annotations = dict(annotations or {})
    narrative_features = [dict(f) for f in (narrative_features or [])]

    # ---- entry points ----------------------------------------------------
    by_module: dict[str, list[str]] = {}
    for entry in reach_report.entry_points:
        by_module.setdefault(entry.module, []).append(entry.ident)
    for idents in by_module.values():
        idents.sort()

    script_modules = {e.module for e in reach_report.entry_points
                      if e.kind == "script"}
    invocations: list[str] = []
    for entry in reach_report.entry_points:
        if entry.kind == "script":
            invocations.append(entry.name)
        elif entry.kind in ("module_main", "main_guard"):
            invocations.append(f"python -m {_dotted(entry.module)}")
    invocations = sorted(set(invocations))

    cli_commands = [
        {"ident": e.ident, "literal": e.name, "module": e.module,
         "function": e.function, "console_script": e.module in script_modules,
         "targets": list(e.targets)}
        for e in sorted(reach_report.entry_points, key=lambda x: x.ident)
        if e.kind == "cli"
    ]
    api_endpoints = [
        {"route": e.name, "method": _method_of(e.function), "module": e.module,
         "function": e.function, "targets": list(e.targets)}
        for e in sorted(reach_report.entry_points, key=lambda x: (x.name, x.function))
        if e.kind == "http"
    ]
    bus_loops = [
        {"ident": e.ident, "module": e.module, "function": e.function}
        for e in sorted(reach_report.entry_points, key=lambda x: x.ident)
        if e.kind == "bus"
    ]

    # ---- env switches ----------------------------------------------------
    dark_by_module: dict[str, list[str]] = {}
    env_vars: list[dict] = []
    for switch in sorted(switch_report.env_switches, key=lambda s: s.name):
        read_in = sorted({site.module for site in switch.sites})
        if switch.dark:
            for module in read_in:
                dark_by_module.setdefault(module, []).append(switch.name)
        ann = annotations.get("env:" + switch.name, {})
        env_vars.append({
            "name": switch.name,
            "read_in": read_in,
            "kind": switch.kind,
            "state": switch.state,
            "default": switch.default,
            "dark": bool(switch.dark),
            "documented": bool(switch.documented),
            "purpose": ann.get("purpose") or "",
        })
    for names in dark_by_module.values():
        names.sort()

    # ---- the module census ----------------------------------------------
    grouped: dict[str, list[dict]] = {}
    status_counts: dict[str, int] = {}
    islands: list[str] = []
    shims: list[str] = []
    unknown: list[str] = []
    for facts in sorted(reach_report.modules, key=lambda m: m.module):
        if facts.classification == "test":
            continue
        rel = facts.module
        ann = annotations.get("module:" + rel, {})
        feature = _feature(rel, facts, by_module.get(rel, ()), dark_by_module, ann)
        grouped.setdefault(_area_of(rel), []).append(feature)
        status_counts[feature["status"]] = status_counts.get(feature["status"], 0) + 1
        if feature["status"] == STATUS_ISLAND:
            islands.append(rel)
        elif feature["status"] == "shim":
            shims.append(rel)
        elif feature["status"] == "unknown":
            unknown.append(rel)

    stale_features, packaging = _stale_features(root, annotations)
    if stale_features:
        grouped[METADATA_AREA] = stale_features
        status_counts[STATUS_STALE] = len(stale_features)

    areas = []
    for name in sorted(grouped):
        ann = annotations.get("area:" + name, {})
        areas.append({
            "area": name,
            "path": name,
            "title": ann.get("title") or "",
            "features": grouped[name],
        })

    # ---- the human blocks that matched nothing ---------------------------
    live_keys = ({"module:" + f["module"] for fs in grouped.values() for f in fs
                  if f.get("module")}
                 | {"env:" + row["name"] for row in env_vars}
                 | {"area:" + a["area"] for a in areas}
                 | {"stale:" + str(f.get("detector") or "") + ":" + str(f.get("name") or "")
                    for f in stale_features})
    unmatched = sorted(k for k in annotations
                       if k not in live_keys and not k.startswith("stale:"))

    if head is None or branch is None or dirty is None:
        stamp = render_mod.git_stamp(root, probe_dirty=probe_dirty)
        head = stamp.revision if head is None else head
        branch = stamp.branch if branch is None else branch
        if dirty is None:
            dirty = (True if stamp.dirty == "dirty"
                     else False if stamp.dirty == "clean" else None)

    doc: dict[str, Any] = {
        "schema": SCHEMA,
        "note": _NOTE,
        "repo_state": {"branch": branch, "head": head, "dirty": dirty},
        "counts": {
            "modules": sum(len(a["features"]) for a in areas),
            "areas": len(areas),
            **{f"status_{k}": v for k, v in sorted(status_counts.items())},
            "entry_points": len(reach_report.entry_points),
            "cli_commands": len(cli_commands),
            "api_endpoints": len(api_endpoints),
            "bus_loops": len(bus_loops),
            "invocations": len(invocations),
            "env_vars": len(env_vars),
            "dark_env_vars": sum(1 for row in env_vars if row["dark"]),
            "islands": len(islands),
            "shims": len(shims),
            "unknown": len(unknown),
            # The count that cannot be lowered by deleting a test.
            "unreached": len(set(islands) | set(shims) | set(unknown)),
            "stale": len(stale_features),
            "packaging_gaps": len(packaging["on_disk_but_unlisted"]),
            "narrative_features": len(narrative_features),
            "annotations": len(annotations),
        },
        "areas": areas,
        "invocations": invocations,
        "cli_commands": cli_commands,
        "api_endpoints": api_endpoints,
        "bus_loops": bus_loops,
        "env_vars": env_vars,
        "packaging": packaging,
        "unparsable": list(reach_report.unparsable),
        "broken_entries": list(reach_report.broken_entries),
        # The prose summaries the previous schema carried. Derived from the
        # SAME pass as the structured features, so the discrepancy the picker
        # reports when the two disagree cannot occur by construction.
        #
        # ``unreached`` is here because the island COUNT is gameable and was
        # demonstrated to be: "island" means unreachable but imported by a
        # test, so deleting the test moves the module to ``unknown`` and the
        # island count goes DOWN while the dead code stays. The union is the
        # number that cannot be improved by deleting a test, and the set diff
        # against the previous run is the honest signal -- not the count.
        "islands": islands,
        "shims": shims,
        "unknown": unknown,
        "unreached": sorted(set(islands) | set(shims) | set(unknown)),
        "stale": [f["reason"] for f in stale_features],
        # human half
        "annotations": {k: annotations[k] for k in sorted(annotations)},
        "narrative_features": narrative_features,
        "unmatched_annotations": unmatched,
    }
    doc[DIGEST_KEY] = _digest(doc)
    return doc


