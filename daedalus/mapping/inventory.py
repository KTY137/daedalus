SCHEMA = "daedalus-feature-inventory/2"

INVENTORY_REL = "docs/FEATURE_INVENTORY.json"

DIGEST_KEY = "digest"

_NOTE = (
    "GENERATED by daedalus.mapping.inventory from the same walk of the tree "
    "that daedalus map performs. Hand-edit ONLY 'annotations', "
    "'narrative_features' and the per-record human fields they feed (name, "
    "kind, notes, purpose, title); every derived field is covered by 'digest'. "
    "Regenerate with: python -m daedalus.mapping.inventory --refresh"
)

# The fields a HUMAN owns on a generated record. They are merged into the
# output so a consumer reads one document, and stripped again before the digest
# so that writing them is not an integrity violation.
FEATURE_HUMAN_FIELDS = ("name", "kind", "notes")
ENV_HUMAN_FIELDS = ("purpose",)
AREA_HUMAN_FIELDS = ("title",)

# Top-level keys the digest never covers: the constant note, the human blocks,
# the digest itself, and the two fields whose value is a function of the human
# blocks (``unmatched_annotations``) or of a clock-adjacent probe that the
# picker explicitly refuses to treat as staleness (``repo_state.dirty``).
_HUMAN_TOP_KEYS = frozenset({
    "note", "annotations", "narrative_features", "unmatched_annotations",
    DIGEST_KEY,
})

# reach classification -> inventory status. ``orphan`` folds into ``island``:
# both mean "no entry point reaches it", and the map's own gate already merges
# them (drift.ISLAND_CLASSES). ``test`` modules are not features and are
# dropped entirely.
STATUS_BY_CLASS = {
    "entry": "wired",
    "reachable": "wired",
    "island": "island",
    "orphan": "island",
    "shim": "shim",
    "unknown": "unknown",
}

STATUS_ISLAND = "island"
STATUS_STALE = "stale"

# Where the mechanically-detected staleness is filed. A distinct area so a
# reader can tell "the tree contradicts this repo's own metadata" from "this
# module is unreachable", which want different verbs.
METADATA_AREA = "(repo metadata)"

# Directories a stale sweep must NOT descend into. Deliberately NOT the same
# set as reach._IGNORE_DIRS: ``build`` and ``__pycache__`` are excluded there
# precisely because they are not source, and they are exactly what this sweep
# is looking for.
_STALE_SKIP_DIRS = frozenset({
    ".git", ".hg", ".svn", "node_modules", ".venv", "venv", "env",
    ".mypy_cache", ".pytest_cache", ".ruff_cache", ".idea", ".vs", ".vscode",
    "vendor", ".cache", "target", "dist", ".daedalus_worktrees",
})

# The HTTP method a route handler implies. web_api dispatches on the request
# method by putting it in the handler's name, so this is a reading of the
# evidence rather than a guess -- and a handler that does not follow the
# convention yields "" rather than a fabricated method.
_METHOD_BY_SUFFIX = (
    ("_handle_delete", "DELETE"), ("_handle_patch", "PATCH"),
    ("_handle_post", "POST"), ("_handle_put", "PUT"), ("_handle_get", "GET"),
)

# Tokens inside a hand-written entrypoint string that could name a module.
# Starts at a letter or underscore so "/api/x" and ".claude/y" do not produce a
# phantom leading-punctuation token.
_TOKEN_RE = re.compile(r"[A-Za-z_][\w./\\-]*")

_SCRIPTS_HEADER = re.compile(r"^\s*\[tool\.setuptools\]\s*$")
_SECTION_RE = re.compile(r"^\s*\[")
_PACKAGES_RE = re.compile(r"^\s*packages\s*=\s*(.*)$")
_QUOTED_RE = re.compile(r"[\"']([^\"']+)[\"']")


